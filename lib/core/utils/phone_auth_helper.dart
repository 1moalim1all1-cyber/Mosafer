/// Firebase Auth (الإصدار المجاني اللي بنستخدمه) بيتطلب بريد إلكتروني +
/// كلمة مرور كطريقة الدخول الأساسية. عشان نوفّر تجربة "تسجيل برقم
/// الموبايل" من غير ما نحتاج بنية تحتية لإرسال SMS حقيقي (OTP) - اللي
/// محتاجة إعداد إضافي معقد وممكن تتكلف على أعداد كبيرة - بنحوّل رقم
/// الموبايل لمعرّف داخلي ثابت وفريد بصيغة بريد إلكتروني، ونستخدمه خلف
/// الكواليس مع Firebase Auth. المستخدم نفسه بيتعامل برقم موبايله بس.
///
/// ملحوظة: ده مش بريد إلكتروني حقيقي وميوصلوش أي رسائل - فمفيش استرجاع
/// كلمة مرور تلقائي عبر إيميل لحسابات اتسجلت بالطريقة دي (راجع
/// forgot_password_screen.dart).
String syntheticEmailFromPhone(String phone) {
  final digitsOnly = phone.replaceAll(RegExp(r'[^0-9]'), '');
  return '$digitsOnly@mosafer.app';
}
